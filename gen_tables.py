#!/usr/bin/env python3
"""Generate the precomputed tables embedded in primes.c.

- PI_TABLE[i] = pi(i * 10000) for i in 0..500 (501 values, N max 5,000,000).
- SMALL_PRIMES: all primes <= 2236 (sqrt(5,000,000) ~ 2236.07).

The reference sieve is an independent odd-only bytearray sieve; its outputs
are cross-checked against known values before emitting the header.
"""
import sys

NMAX = 5_000_000
STEP = 10_000
SQRT = 2236

def sieve(n):
    # odd-only sieve; sieve[i] corresponds to number 2*i+1
    size = (n + 1) // 2
    s = bytearray(b"\x01") * size
    s[0] = 0  # 1 is not prime
    import math
    for i in range(3, int(math.isqrt(n)) + 1, 2):
        if s[i // 2]:
            step = i
            start = i * i // 2
            s[start:size:step] = b"\x00" * ((size - 1 - start) // step + 1)
    return s

def main():
    s = sieve(NMAX)
    # pi array for verification of a few known values
    pi = [0] * (NMAX + 1)
    c = 0
    # pi(0)=pi(1)=0; 2 is prime
    for n in range(2, NMAX + 1):
        if n == 2 or (n % 2 == 1 and s[n // 2]):
            c += 1
        pi[n] = c
    known = {10: 4, 100: 25, 1000: 168, 100000: 9592,
             1000000: 78498, 5000000: 348513}
    for n, want in known.items():
        got = pi[n]
        assert got == want, f"pi({n}) = {got}, want {want}"
    print("reference sieve OK:", {n: pi[n] for n in known}, file=sys.stderr)

    table = [pi[i * STEP] for i in range(NMAX // STEP + 1)]
    assert len(table) == 501
    small = [p for p in range(2, SQRT + 1)
             if p == 2 or (p % 2 == 1 and s[p // 2])]
    assert small[-1] == 2221, small[-3:]  # 2233 = 7*11*29, composite
    print(f"small primes <= 2236: {len(small)}", file=sys.stderr)

    def fmt(arr, per=10):
        lines = []
        for i in range(0, len(arr), per):
            lines.append("    " + ", ".join(str(x) for x in arr[i:i + per]) + ",")
        return "\n".join(lines)

    with open("tables.h", "w") as f:
        f.write("/* Generated by gen_tables.py — do not hand-edit. */\n")
        f.write("/* PI_TABLE[i] = pi(i*10000), i in 0..500. SMALL_PRIMES: primes <= 2236. */\n")
        f.write("#pragma once\n\n")
        f.write("static const int PI_TABLE[501] = {\n" + fmt(table) + "\n};\n\n")
        f.write(f"static const int SMALL_PRIMES[{len(small)}] = {{\n" + fmt(small) + "\n};\n")
        f.write(f"\n#define NSMALL {len(small)}\n")
    print("wrote tables.h", file=sys.stderr)

if __name__ == "__main__":
    main()
